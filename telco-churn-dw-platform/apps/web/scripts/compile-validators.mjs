// Precompile the record JSON Schema into plain JavaScript (Ajv standalone).
// The browser then never calls `new Function`, so the CSP can forbid 'unsafe-eval'.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const schema = JSON.parse(readFileSync(join(here, "../src/contracts/telco-record.v1.schema.json"), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
const outDir = join(here, "../src/lib/generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "record-validator.js"), `// Generated by scripts/compile-validators.mjs - do not edit.\n${standaloneCode(ajv, validate)}`);
writeFileSync(
  join(outDir, "record-validator.d.ts"),
  `// Generated by scripts/compile-validators.mjs - do not edit.
import type { ErrorObject } from "ajv";
declare const validate: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };
export default validate;
`,
);
console.log("record validator compiled to src/lib/generated/record-validator.js");
